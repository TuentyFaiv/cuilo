//! `cargo xtask docs`: the docs site's generated pages and data, built from the CLI, the JSON Schemas and the
//! official packs, so the reference never drifts from the code.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::{Map, Value, json};

use crate::release::root;

/// The CLI reference pages, one per command plus an index.
const CLI_DIR: &str = "apps/docs/src/content/docs/reference/cli";
/// The reference pages built from JSON Schemas.
const REFERENCE_DIR: &str = "apps/docs/src/content/docs/reference";
/// Pack data the directory and pack pages read.
const PACKS_JSON: &str = "apps/docs/src/data/packs.json";
/// Marks a page as generated, for anyone opening the file.
const NOTICE: &str = "<!-- Generated by `cargo xtask docs`; edit the source it names instead. -->";
/// How deep nested schema fields are listed.
const MAX_DEPTH: usize = 3;

/// One reference page built from a JSON Schema in `schemas/`.
struct SchemaPage {
	schema: &'static str,
	slug: &'static str,
	title: &'static str,
}

const SCHEMA_PAGES: [SchemaPage; 5] = [
	SchemaPage {
		schema: "config",
		slug: "configuration",
		title: "cuilo.json",
	},
	SchemaPage {
		schema: "user-config",
		slug: "user-config",
		title: "User config",
	},
	SchemaPage {
		schema: "lock",
		slug: "lockfile",
		title: "cuilo.lock",
	},
	SchemaPage {
		schema: "pack",
		slug: "pack-manifest",
		title: "pack.toml",
	},
	SchemaPage {
		schema: "piece",
		slug: "piece-manifest",
		title: "piece.toml",
	},
];

/// Writes the generated files, or with `check`, fails listing the ones that differ from what the code gives.
pub(crate) fn run(check: bool) -> Result<(), String> {
	let root = root();
	let files = generate(&root)?;
	let stale = stale_cli_pages(&root, &files)?;
	if check {
		let mut problems: Vec<String> = files
			.iter()
			.filter(|(path, text)| fs::read_to_string(root.join(path)).ok().as_deref() != Some(text.as_str()))
			.map(|(path, _)| format!("{} is out of date", path.display()))
			.collect();
		problems.extend(
			stale
				.iter()
				.map(|path| format!("{} has no command any more", path.display())),
		);
		return if problems.is_empty() {
			Ok(())
		} else {
			Err(format!(
				"{}\nrun `cargo xtask docs` and commit the result",
				problems.join("\n")
			))
		};
	}
	for (path, text) in &files {
		let target = root.join(path);
		if let Some(parent) = target.parent() {
			fs::create_dir_all(parent).map_err(|error| format!("could not create {}: {error}", parent.display()))?;
		}
		fs::write(&target, text).map_err(|error| format!("could not write {}: {error}", target.display()))?;
		eprintln!("wrote {}", path.display());
	}
	for path in stale {
		fs::remove_file(root.join(&path)).map_err(|error| format!("could not remove {}: {error}", path.display()))?;
		eprintln!("removed {}", path.display());
	}
	Ok(())
}

/// Every generated file, by path relative to the repository root.
fn generate(root: &Path) -> Result<BTreeMap<PathBuf, String>, String> {
	let mut files = BTreeMap::new();
	let cli = cuilo(root, &["--json", "man"])?;
	files.insert(Path::new(CLI_DIR).join("index.md"), cli_index(&cli));
	for (index, command) in list(&cli["commands"]).enumerate() {
		let name = text(&command["name"]);
		files.insert(
			Path::new(CLI_DIR).join(format!("{name}.md")),
			command_page(command, index + 1),
		);
	}
	for page in &SCHEMA_PAGES {
		let path = root.join("schemas").join(format!("{}.schema.json", page.schema));
		let schema = read_json(&path)?;
		files.insert(
			Path::new(REFERENCE_DIR).join(format!("{}.md", page.slug)),
			schema_page(page, &schema),
		);
	}
	files.insert(PathBuf::from(PACKS_JSON), packs(root)?);
	Ok(files)
}

/// CLI pages on disk that no command generates any more.
fn stale_cli_pages(root: &Path, files: &BTreeMap<PathBuf, String>) -> Result<Vec<PathBuf>, String> {
	let dir = root.join(CLI_DIR);
	let Ok(entries) = fs::read_dir(&dir) else {
		return Ok(Vec::new());
	};
	let mut stale = Vec::new();
	for entry in entries {
		let entry = entry.map_err(|error| format!("could not list {}: {error}", dir.display()))?;
		let path = Path::new(CLI_DIR).join(entry.file_name());
		if !files.contains_key(&path) {
			stale.push(path);
		}
	}
	stale.sort();
	Ok(stale)
}

/// Runs this workspace's `cuilo` with `args` in an empty project and user folder, and parses its JSON output.
fn cuilo(root: &Path, args: &[&str]) -> Result<Value, String> {
	let scratch = root.join("target/xtask-docs");
	for dir in ["project", "config", "cache"] {
		fs::create_dir_all(scratch.join(dir))
			.map_err(|error| format!("could not create {}: {error}", scratch.display()))?;
	}
	let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
	let output = Command::new(cargo)
		.args(["run", "--quiet", "--locked", "--package", "cuilo", "--"])
		.args(args)
		.current_dir(scratch.join("project"))
		.env("CUILO_CONFIG_DIR", scratch.join("config"))
		.env("CUILO_CACHE_DIR", scratch.join("cache"))
		.env("NO_COLOR", "1")
		.output()
		.map_err(|error| format!("could not run cuilo: {error}"))?;
	if !output.status.success() {
		return Err(format!(
			"`cuilo {}` failed: {}",
			args.join(" "),
			String::from_utf8_lossy(&output.stderr).trim()
		));
	}
	serde_json::from_slice(&output.stdout).map_err(|error| format!("`cuilo {}` printed no JSON: {error}", args.join(" ")))
}

fn read_json(path: &Path) -> Result<Value, String> {
	let text = fs::read_to_string(path).map_err(|error| format!("could not read {}: {error}", path.display()))?;
	serde_json::from_str(&text).map_err(|error| format!("{} is not JSON: {error}", path.display()))
}

fn list(value: &Value) -> impl Iterator<Item = &Value> {
	value.as_array().into_iter().flatten()
}

fn text(value: &Value) -> &str {
	value.as_str().unwrap_or_default()
}

/// `text` ending in a full stop, as the CLI leaves the last one off.
fn sentence(text: &str) -> String {
	let text = text.trim();
	if text.is_empty() || text.ends_with(['.', '!', '?', ':', ')']) {
		text.to_owned()
	} else {
		format!("{text}.")
	}
}

/// `text` safe inside a Markdown table cell.
fn cell(text: &str) -> String {
	text.replace('|', "\\|").replace('\n', " ")
}

/// `text` as a quoted YAML string, without Markdown code marks.
fn yaml(text: &str) -> String {
	Value::String(text.replace('`', "")).to_string()
}

fn front_matter(title: &str, description: &str, generated: &str, sidebar: Option<(&str, usize)>) -> String {
	let mut out = format!(
		"---\ntitle: {}\ndescription: {}\ngenerated: {}\neditUrl: false\n",
		yaml(title),
		yaml(description),
		yaml(generated)
	);
	if let Some((label, order)) = sidebar {
		let _ = write!(out, "sidebar:\n  label: {}\n  order: {order}\n", yaml(label));
	}
	let _ = write!(out, "---\n\n{NOTICE}\n\n");
	out
}

/// How an argument is written on the command line, e.g. `-i, --input <KEY=VALUE>`.
fn arg_syntax(arg: &Value) -> String {
	let names: Vec<String> = list(&arg["value_names"]).map(|name| text(name).to_owned()).collect();
	let value = names
		.first()
		.cloned()
		.unwrap_or_else(|| text(&arg["id"]).to_uppercase());
	if arg["positional"] == true {
		return if arg["required"] == true {
			format!("<{value}>")
		} else {
			format!("[{value}]")
		};
	}
	let mut syntax = String::new();
	if let Some(short) = arg["short"].as_str() {
		let _ = write!(syntax, "-{short}, ");
	}
	let _ = write!(syntax, "--{}", text(&arg["long"]));
	if arg["takes_value"] == true {
		let _ = write!(syntax, " <{value}>");
	}
	syntax
}

fn arg_description(arg: &Value) -> String {
	let mut out = sentence(text(&arg["help"]));
	let values: Vec<String> = list(&arg["possible_values"])
		.map(|value| format!("`{}`", text(value)))
		.collect();
	if !values.is_empty() {
		let _ = write!(out, " One of {}.", values.join(", "));
	}
	let defaults: Vec<String> = list(&arg["defaults"])
		.map(|value| format!("`{}`", text(value)))
		.collect();
	if !defaults.is_empty() && arg["takes_value"] == true {
		let _ = write!(out, " Default: {}.", defaults.join(", "));
	}
	if arg["repeatable"] == true {
		out.push_str(" Repeatable.");
	}
	out
}

fn arg_table(out: &mut String, heading: &str, column: &str, args: &[&Value]) {
	if args.is_empty() {
		return;
	}
	let _ = write!(out, "{heading}\n\n| {column} | Description |\n| --- | --- |\n");
	for arg in args {
		let _ = writeln!(
			out,
			"| `{}` | {} |",
			cell(&arg_syntax(arg)),
			cell(&arg_description(arg))
		);
	}
	out.push('\n');
}

/// Usage, arguments and options of one command, under headings of `level`.
fn command_body(out: &mut String, command: &Value, level: &str) {
	let _ = write!(out, "{level} Usage\n\n```sh\n{}\n```\n\n", text(&command["usage"]));
	let args: Vec<&Value> = list(&command["args"]).filter(|arg| arg["global"] != true).collect();
	let positional: Vec<&Value> = args.iter().copied().filter(|arg| arg["positional"] == true).collect();
	let options: Vec<&Value> = args.iter().copied().filter(|arg| arg["positional"] != true).collect();
	arg_table(out, &format!("{level} Arguments"), "Argument", &positional);
	arg_table(out, &format!("{level} Options"), "Option", &options);
}

fn cli_index(cli: &Value) -> String {
	let mut out = front_matter(
		"CLI",
		"Every cuilo command and flag, generated from the CLI itself.",
		"cuilo --json man",
		Some(("Overview", 0)),
	);
	let _ = write!(
		out,
		"{}\n\n## Usage\n\n```sh\n{}\n```\n\n",
		sentence(text(&cli["about"])),
		text(&cli["usage"])
	);
	out.push_str("## Commands\n\n| Command | Description |\n| --- | --- |\n");
	for command in list(&cli["commands"]) {
		let name = text(&command["name"]);
		let _ = writeln!(
			out,
			"| [`{name}`](/reference/cli/{name}/) | {} |",
			cell(&sentence(text(&command["about"])))
		);
	}
	out.push('\n');
	let globals: Vec<&Value> = list(&cli["args"]).collect();
	arg_table(
		&mut out,
		"## Global options\n\nThese work with every command.",
		"Option",
		&globals,
	);
	out.push_str("## Exit codes\n\nSee [Exit codes](/reference/exit-codes/).\n");
	out
}

fn command_page(command: &Value, order: usize) -> String {
	let name = text(&command["name"]);
	let about = sentence(text(&command["about"]));
	let mut out = front_matter(text(&command["path"]), &about, "cuilo --json man", Some((name, order)));
	let _ = write!(out, "{about}\n\n");
	let subcommands: Vec<&Value> = list(&command["commands"]).collect();
	if subcommands.is_empty() {
		command_body(&mut out, command, "##");
	} else {
		out.push_str("## Commands\n\n| Command | Description |\n| --- | --- |\n");
		for sub in &subcommands {
			let path = text(&sub["path"]);
			let anchor = path.replace(' ', "-");
			let _ = writeln!(
				out,
				"| [`{path}`](#{anchor}) | {} |",
				cell(&sentence(text(&sub["about"])))
			);
		}
		out.push('\n');
		for sub in subcommands {
			let _ = write!(
				out,
				"## {}\n\n{}\n\n",
				text(&sub["path"]),
				sentence(text(&sub["about"]))
			);
			command_body(&mut out, sub, "###");
		}
	}
	out.push_str(
		"## Global options\n\n`--root`, `--json` and `--no-input` work here too; see [global options](/reference/cli/#global-options).\n",
	);
	out
}

/// A schema field to list: its dotted path, types, whether it is required, and its description.
struct Field {
	path: String,
	types: Vec<String>,
	required: bool,
	description: String,
	values: Vec<String>,
	default: Option<String>,
	/// Which variants of a union have this field, when not all do.
	only: Option<String>,
	depth: usize,
}

fn resolve<'a>(schema: &'a Value, node: &'a Value) -> (&'a Value, Option<&'a str>) {
	match node["$ref"]
		.as_str()
		.and_then(|reference| reference.strip_prefix("#/$defs/"))
	{
		Some(name) => (&schema["$defs"][name], Some(name)),
		None => (node, None),
	}
}

/// Readable type names of `node`, leaving out `null`.
fn type_names(schema: &Value, node: &Value) -> Vec<String> {
	let names = known_types(schema, node);
	if names.is_empty() {
		vec!["any".to_owned()]
	} else {
		names
	}
}

/// The type names `node` states; empty for `null` alone or a node that states none.
fn known_types(schema: &Value, node: &Value) -> Vec<String> {
	let (node, reference) = resolve(schema, node);
	let variants: Vec<&Value> = list(&node["anyOf"]).chain(list(&node["oneOf"])).collect();
	if !variants.is_empty() {
		let mut names: Vec<String> = variants
			.iter()
			.flat_map(|variant| known_types(schema, variant))
			.collect();
		names.dedup();
		return names;
	}
	let kinds: Vec<&str> = match &node["type"] {
		Value::String(kind) => vec![kind.as_str()],
		Value::Array(kinds) => kinds.iter().filter_map(Value::as_str).collect(),
		_ => Vec::new(),
	};
	let mut names = Vec::new();
	for kind in kinds.into_iter().filter(|kind| *kind != "null") {
		names.push(match kind {
			"array" => format!("array of {}", type_names(schema, &node["items"]).join(" or ")),
			"object" if node["additionalProperties"].is_object() => {
				format!(
					"map of {}",
					type_names(schema, &node["additionalProperties"]).join(" or ")
				)
			}
			"integer" | "number" => "number".to_owned(),
			other => other.to_owned(),
		});
	}
	if names.is_empty()
		&& let Some(reference) = reference
	{
		names.push(reference.to_lowercase());
	}
	names
}

/// The objects whose properties `node` describes, one per union variant, and the suffix that reaches their
/// fields (`[]` for items, `.<key>` for map values).
fn objects_of<'a>(schema: &'a Value, node: &'a Value) -> (Vec<&'a Value>, &'static str) {
	let (node, _) = resolve(schema, node);
	if node["properties"].is_object() {
		return (vec![node], "");
	}
	let mut objects = Vec::new();
	let mut suffix = "";
	for variant in list(&node["anyOf"]).chain(list(&node["oneOf"])) {
		let (found, found_suffix) = objects_of(schema, variant);
		if !found.is_empty() {
			suffix = found_suffix;
		}
		objects.extend(found);
	}
	if !objects.is_empty() {
		return (objects, suffix);
	}
	if node["items"].is_object() {
		return (objects_of(schema, &node["items"]).0, "[]");
	}
	if node["additionalProperties"].is_object() {
		return (objects_of(schema, &node["additionalProperties"]).0, ".<key>");
	}
	(Vec::new(), "")
}

/// The `type` constant that tells a union's object variants apart, e.g. `"bool"`.
fn tag(object: &Value) -> Option<&str> {
	object["properties"]["type"]["const"].as_str()
}

/// Pushes the fields of `objects`, the variants of one object, merging fields they share.
fn fields(schema: &Value, objects: &[&Value], prefix: &str, depth: usize, out: &mut Vec<Field>) {
	let mut names: Vec<&String> = Vec::new();
	for object in objects {
		for name in object["properties"].as_object().into_iter().flat_map(Map::keys) {
			if !names.contains(&name) {
				names.push(name);
			}
		}
	}
	for name in names {
		let holders: Vec<&Value> = objects
			.iter()
			.copied()
			.filter(|object| object["properties"].get(name).is_some())
			.collect();
		let nodes: Vec<&Value> = holders.iter().map(|object| &object["properties"][name]).collect();
		let path = if prefix.is_empty() {
			name.clone()
		} else {
			format!("{prefix}.{name}")
		};
		let mut types = Vec::new();
		let mut values = Vec::new();
		for node in &nodes {
			for kind in type_names(schema, node) {
				if !types.contains(&kind) {
					types.push(kind);
				}
			}
			let (resolved, _) = resolve(schema, node);
			let constant = Some(&resolved["const"]).filter(|value| !value.is_null());
			for value in list(&resolved["enum"]).chain(constant) {
				let shown = format!("`{}`", value.as_str().map_or_else(|| value.to_string(), str::to_owned));
				if !values.contains(&shown) {
					values.push(shown);
				}
			}
		}
		let description = nodes
			.iter()
			.find_map(|node| {
				node["description"]
					.as_str()
					.or_else(|| resolve(schema, node).0["description"].as_str())
			})
			.unwrap_or_default();
		let tags: Vec<String> = holders
			.iter()
			.filter_map(|object| tag(object))
			.map(|tag| format!("`{tag}`"))
			.collect();
		let only = (holders.len() < objects.len() && tags.len() == holders.len())
			.then(|| format!("Only when `type` is {}.", tags.join(" or ")));
		out.push(Field {
			path: path.clone(),
			types,
			required: holders
				.iter()
				.all(|object| list(&object["required"]).any(|required| required == name.as_str())),
			description: sentence(description),
			values,
			default: nodes
				.iter()
				.find_map(|node| node.get("default").filter(|value| !value.is_null()))
				.map(Value::to_string),
			only,
			depth,
		});
		if depth < MAX_DEPTH {
			let mut children = Vec::new();
			let mut suffix = "";
			for node in &nodes {
				let (found, found_suffix) = objects_of(schema, node);
				if !found.is_empty() {
					suffix = found_suffix;
				}
				children.extend(found);
			}
			if !children.is_empty() {
				fields(schema, &children, &format!("{path}{suffix}"), depth + 1, out);
			}
		}
	}
}

fn schema_page(page: &SchemaPage, schema: &Value) -> String {
	let description = sentence(text(&schema["description"]));
	let mut out = front_matter(
		page.title,
		&description,
		&format!("schemas/{}.schema.json", page.schema),
		None,
	);
	let _ = write!(
		out,
		"{description}\n\nEditors can complete and check this file with its JSON Schema, [`{}.schema.json`](https://github.com/TuentyFaiv/cuilo/blob/main/schemas/{}.schema.json).\n\n## Fields\n\n",
		page.schema, page.schema
	);
	let mut list_of = Vec::new();
	fields(schema, &[schema], "", 0, &mut list_of);
	for field in list_of {
		let heading = "#".repeat((field.depth + 3).min(6));
		let presence = if field.required { "required" } else { "optional" };
		let _ = write!(
			out,
			"{heading} `{}`\n\n**Type:** {} · {presence}\n\n",
			field.path,
			field
				.types
				.iter()
				.map(|kind| format!("`{kind}`"))
				.collect::<Vec<_>>()
				.join(" or ")
		);
		if !field.description.is_empty() {
			let _ = write!(out, "{}\n\n", field.description);
		}
		if let Some(only) = field.only {
			let _ = write!(out, "{only}\n\n");
		}
		if !field.values.is_empty() {
			let _ = write!(out, "One of {}.\n\n", field.values.join(", "));
		}
		if let Some(default) = field.default {
			let _ = write!(out, "Default: `{default}`.\n\n");
		}
	}
	out.truncate(out.trim_end().len());
	out.push('\n');
	out
}

/// The official packs as the directory and pack pages show them.
fn packs(root: &Path) -> Result<String, String> {
	let mut packs = Vec::new();
	for pack in list(&cuilo(root, &["--json", "pack", "list"])?) {
		let name = text(&pack["name"]);
		let shown = cuilo(root, &["--json", "pack", "show", name])?;
		let manifest = manifest(root, name)?;
		let pieces: Vec<Value> = list(&shown["pieces"]).map(piece).collect();
		packs.push(json!({
			"name": name,
			"version": pack["version"],
			"description": pack["description"],
			"source": pack["source"],
			"license": manifest.get("license").and_then(toml::Value::as_str),
			"permissions": {
				"write": manifest.get("permissions").and_then(|permissions| permissions.get("write")).and_then(toml::Value::as_array).map(|globs| globs.iter().filter_map(toml::Value::as_str).collect::<Vec<_>>()),
				"dependencies": manifest.get("permissions").and_then(|permissions| permissions.get("dependencies")).and_then(toml::Value::as_bool).unwrap_or(false),
			},
			"pieces": pieces,
		}));
	}
	let mut text = serde_json::to_string_pretty(&packs).map_err(|error| format!("could not write pack data: {error}"))?;
	text.push('\n');
	Ok(text)
}

fn manifest(root: &Path, name: &str) -> Result<toml::Table, String> {
	let path = root.join("packs").join(name).join("pack.toml");
	let text = fs::read_to_string(&path).map_err(|error| format!("could not read {}: {error}", path.display()))?;
	text
		.parse()
		.map_err(|error| format!("{} is not TOML: {error}", path.display()))
}

fn piece(piece: &Value) -> Value {
	let mut inputs: Vec<(&String, &Value)> = piece["inputs"]
		.as_object()
		.map(Map::iter)
		.into_iter()
		.flatten()
		.collect();
	inputs.sort_by_key(|(name, _)| (name.as_str() != "name", name.as_str()));
	let inputs: Vec<Value> = inputs
		.into_iter()
		.map(|(name, input)| {
			json!({
				"name": name,
				"type": input["type"],
				"description": input["description"],
				"default": input.get("default"),
				"example": input.get("example"),
			})
		})
		.collect();
	let mut variants: Vec<&str> = list(&piece["variants"]).map(|variant| text(&variant["name"])).collect();
	variants.dedup();
	let dependencies: Vec<Value> = list(&piece["dependencies"])
		.map(|dependency| {
			json!({
				"ecosystem": dependency["ecosystem"],
				"name": dependency["name"],
				"version": dependency["version"],
				"dev": dependency["dev"],
			})
		})
		.collect();
	json!({
		"name": piece["name"],
		"kind": piece["kind"],
		"description": piece["description"],
		"target": piece["target"],
		"inputs": inputs,
		"variants": variants,
		"dependencies": dependencies,
	})
}

